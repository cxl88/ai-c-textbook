def h(t, lv=1):
    d.add_heading(t, lv)


def p(t):
    d.add_paragraph(t)


def li(t):
    d.add_paragraph(t, style='List Bullet')


def code(t):
    for ln in t.strip('\n').split('\n'):
        para = d.add_paragraph()
        para.paragraph_format.space_after = Pt(0)
        r = para.add_run(ln)
        r.font.name = 'Consolas'
        r.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
        r.font.size = Pt(9)


def tbl(rows, widths=None):
    t = d.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = 'Table Grid'
    if widths:  # 列宽同时写入 gridCol（LibreOffice）和单元格（Word）
        t.autofit = False
        for j, w in enumerate(widths):
            t.columns[j].width = Cm(w)
    for i, r in enumerate(rows):
        for j, c in enumerate(r):
            t.cell(i, j).text = c
            if widths:
                t.cell(i, j).width = Cm(widths[j])
            if i == 0:
                for run in t.cell(i, j).paragraphs[0].runs:
                    run.bold = True


