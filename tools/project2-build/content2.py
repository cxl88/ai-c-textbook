def lines(name, a, z):
    return '\n'.join(src(name).split('\n')[a - 1:z])


def fill(text, old, new):
    """把程序中的 old 换成填空 new，行尾注释仍对齐在原来的列（按 IDE 列数，汉字占 2 列）"""
    out = []
    for ln in text.split('\n'):
        i = ln.find(old)
        if i >= 0:
            k = ln.find('//', i + len(old))
            if k >= 0:
                head = ln[:i] + new + ln[i + len(old):k].rstrip()
                ln = head + ' ' * max(1, _vw(ln[:k], 2) - _vw(head, 2)) + ln[k:]
            else:
                ln = ln[:i] + new + ln[i + len(old):]
        out.append(ln)
    return '\n'.join(out)


