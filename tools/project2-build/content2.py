CTRL = 'NUL SOH STX ETX EOT ENQ ACK BEL BS HT LF VT FF CR SO SI DLE DC1 DC2 DC3 DC4 NAK SYN ETB CAN EM SUB ESC FS GS RS US'.split()


def ch(n):
    if n < 32:
        return CTRL[n]
    if n == 32:
        return 'SP'
    if n == 127:
        return 'DEL'
    return chr(n)


