def rd(name, ext):
    for d in (BOOK, CHECK):
        f = f'{d}/{name}.{ext}'
        if os.path.exists(f):
            return open(f, encoding='utf8').read()
    raise FileNotFoundError(f'{name}.{ext}')


def wo(name, s=''):
    return rd(name, 'wout' + s)


def diag(name):
    return rd(name, 'wdiag')


NCHK = [0]


def chk(name, s, *texts):
    """断言实测输出中含有这些文字"""
    w = wo(name, s)
    for t in texts:
        assert t in w, (name, s, t, w)
        NCHK[0] += 1


def nchk(name, s, *texts):
    """断言实测输出中没有这些文字"""
    w = wo(name, s)
    for t in texts:
        assert t not in w, (name, s, t, w)
        NCHK[0] += 1


def dchk(name, *texts):
    """断言编译提示中含有这些文字"""
    w = diag(name)
    for t in texts:
        assert t in w, (name, t, w)
        NCHK[0] += 1


def ok(cond, what):
    assert cond, what
    NCHK[0] += 1


