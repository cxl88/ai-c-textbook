def h(t, lv=1):
    d.add_heading(t, lv)


def p(t, lead=None):
    para = d.add_paragraph()
    if lead:
        para.add_run(lead).bold = True
    para.add_run(t)


def li(t):
    d.add_paragraph(t, style='List Bullet')


def tbl(rows, widths):
    t = d.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = 'Table Grid'
    t.autofit = False
    for j, w in enumerate(widths):  # 列宽同时写入 gridCol（LibreOffice）和单元格（Word）
        t.columns[j].width = Cm(w)
    for i, r in enumerate(rows):
        for j, c in enumerate(r):
            t.cell(i, j).text = c
            t.cell(i, j).width = Cm(widths[j])
            for para in t.cell(i, j).paragraphs:
                for run in para.runs:
                    run.font.size = Pt(9.5)
                    if i == 0:
                        run.bold = True




