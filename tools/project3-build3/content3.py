def kn(p):
    """与下段同页"""
    ppr = p.find(W + 'pPr')
    if ppr.find(W + 'keepNext') is None:
        st = ppr.find(W + 'pStyle')
        (st.addnext if st is not None else lambda e: ppr.insert(0, e))(etree.Element(W + 'keepNext'))
    return p


def nokeep(p):
    """不必与下段同页（覆盖样式中的“与下段同页”）"""
    ppr = p.find(W + 'pPr')
    for e in ppr.findall(W + 'keepNext'):
        ppr.remove(e)
    e = etree.Element(W + 'keepNext')
    e.set(W + 'val', '0')
    st = ppr.find(W + 'pStyle')
    (st.addnext if st is not None else lambda x: ppr.insert(0, x))(e)
    return p


def center(p):
    ppr = p.find(W + 'pPr')
    jc = ppr.find(W + 'jc')
    if jc is None:
        jc = etree.SubElement(ppr, W + 'jc')
    jc.set(W + 'val', 'center')
    ind = ppr.find(W + 'ind')
    if ind is not None:
        ppr.remove(ind)
    return p


