def rd(name, ext):
    for d in (BOOK, CHECK):
        f = f'{d}/{name}.{ext}'
        if os.path.exists(f):
            return open(f, encoding='utf8').read()
    raise FileNotFoundError(f'{name}.{ext}')


def wo(name, s=''):
    return rd(name, 'wout' + s)


def diag(name):
    return rd(name, 'wdiag')


def cap(name):
    """限时运行记录：(是否超时, 输出行数, 输出字节数)"""
    w = rd(name, 'wcapret').split()            # 如 timeout 5s lines=N bytes=M
    return w[0] == 'timeout', int(w[-2].split('=')[1]), int(w[-1].split('=')[1])


NCHK = [0]


def chk(name, s, *texts):
    """断言实测输出中含有这些文字"""
    w = wo(name, s)
    for t in texts:
        assert t in w, (name, s, t, w)
        NCHK[0] += 1


def nchk(name, s, *texts):
    """断言实测输出中没有这些文字"""
    w = wo(name, s)
    for t in texts:
        assert t not in w, (name, s, t, w)
        NCHK[0] += 1


def ok(cond, what):
    assert cond, what
    NCHK[0] += 1


