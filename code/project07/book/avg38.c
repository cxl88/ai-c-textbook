/* 程序名：avg38.c
   功能：求每个测点 3 轮的平均电压（任务二 技能训练 1） */
#include <stdio.h>

int main(void)
{
    float v[3][8] = {
        {4.02, 3.98, 12.00, 4.05, 3.42, 0.00, 3.96, 4.01},
        {4.01, 3.99, 12.00, 4.03, 3.67, 0.00, 3.97, 4.02},
        {4.03, 3.97, 12.00, 4.04, 3.15, 0.00, 3.95, 4.00}};
    float sum;                         // 一个测点 3 轮电压之和
    int i, j;

    for (j = 0; j < 8; j++)            // 外层：逐个测点（列）
    {
        sum = 0;
        for (i = 0; i < 3; i++)        // 内层：逐轮（行）
        {
            sum = sum + v[i][j];
        }
        printf("V%d的平均电压：%.2f V\n", j + 1, sum / 3);
    }
    return 0;
}
