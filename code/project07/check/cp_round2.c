/* 程序名：cp_round2.c
   功能：课堂练习参考答案：输出第 2 轮的 8 个电压 */
#include <stdio.h>

int main(void)
{
    float v[3][8] = {
        {4.02, 3.98, 12.00, 4.05, 3.42, 0.00, 3.96, 4.01},
        {4.01, 3.99, 12.00, 4.03, 3.67, 0.00, 3.97, 4.02},
        {4.03, 3.97, 12.00, 4.04, 3.15, 0.00, 3.95, 4.00}};
    int j;

    for (j = 0; j < 8; j++)
    {
        printf("%.2f ", v[1][j]);
    }
    printf("\n");
    return 0;
}
