#include <stdio.h>                        // 包含标准输入输出头文件

int main(void)                            // 主函数：程序从这里开始执行
{                                         // 函数体开始
    printf("上午报到：%d 人\n", 1268);        // %d 处输出整数 1268
    printf("下午报到：%d 人\n", 532);         // %d 处输出整数 532
    printf("今日合计：%d 人\n", 1268 + 532);  // 先算出 1268+532，再输出
    return 0;                             // 结束程序，向系统返回 0
}                                         // 函数体结束
